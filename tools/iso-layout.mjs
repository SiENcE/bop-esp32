// The game's numbers for a street-mode room, measured from its map (art/rooms/<id>.map.js, art/lib/isomap.js):
// walk area and holes, each prop's front line, baseline and shape, the spots and the lamps.
// Usage: node tools/iso-layout.mjs <id> [--out game/rooms/<id>.layout.js] [--json]
// Without --out it prints a summary (and the JSON with --json).
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const [id, ...rest] = process.argv.slice(2);
if (!id) { console.error("usage: node tools/iso-layout.mjs <id> [--out file] [--json]"); process.exit(2); }
const out = rest.includes("--out") ? rest[rest.indexOf("--out") + 1] : null;

const ctx = vm.createContext({});
for (const f of ["art/lib/isomap.js", `art/rooms/${id}.map.js`]) vm.runInContext(readFileSync(f, "utf8"), ctx, { filename: f });
const L = vm.runInContext(`ISOMAP.layout(ISO_MAPS[${JSON.stringify(id)}])`, ctx);
const json = JSON.parse(JSON.stringify(L));

if (out) {
  const body = `// generated by tools/iso-layout.mjs from art/rooms/${id}.map.js: never edit by hand, change the map\n"use strict";\n\n` +
    `Halcyon.layouts = Halcyon.layouts || {};\nHalcyon.layouts[${JSON.stringify(id)}] = ${JSON.stringify(json)};\n`;
  writeFileSync(out, body);
  console.log(`wrote ${out}`);
}
const n = (a) => a.length / 2;
console.log(`${id}: walk ${json.walk.length} loop(s) (${json.walk.map(n).join(", ")} points), holes ${json.holes.length}, props ${Object.keys(json.props).length}, spots ${Object.keys(json.spots).length}, lamps ${json.lamps.length}`);
if (rest.includes("--json")) console.log(JSON.stringify(json, null, 1));
