// A painted room's moving parts and runtime lamps as a script the game loads (the game has no fetch): the room's build prints them
// as a line "PARTS {json}" (tools/build_art.sh keeps it in art/rooms/<id>.parts.json); this writes game/rooms/<id>.parts.js with
// Nagiwa.parts.<id> = { room, size, parts: [{ name, at, size, frames, fps, layer }], lamps: [[x, y, "#hex", radius], ...] }.
//   node tools/room-parts.mjs <id>
import { readFileSync, writeFileSync } from "node:fs";

const id = process.argv[2];
if (!id) { console.error("usage: node tools/room-parts.mjs <id>"); process.exit(2); }
const json = JSON.parse(readFileSync(`art/rooms/${id}.parts.json`, "utf8"));
writeFileSync(`game/rooms/${id}.parts.js`,
  `// generated by tools/room-parts.mjs from art/rooms/${id}.px.js (its PARTS line, tools/build_art.sh room ${id}): never edit by hand;\n` +
  `// change the painting and build the room again\n"use strict";\n\nNagiwa.parts = Nagiwa.parts || {};\nNagiwa.parts[${JSON.stringify(id)}] = ${JSON.stringify(json)};\n`);
console.log(`game/rooms/${id}.parts.js: ${json.parts.length} parts, ${json.lamps.length} lamps`);
