// The ways between the rooms Juno walks, read from the game for the city's plan (docs/plan): every hotspot's exit and every goto
// in a hotspot's scripts, with where it is (the hotspot's walk-to point, else its shape's middle) and where it arrives (the goto's
// or exit's `at`), in room pixels. Rooms that are only watched (the cameras, the deck, shots) are left out: watching isn't walking.
// Writes docs/plan/uebergaenge.js (generated: never edit), which docs/plan/index.html draws as arrows from door to door.
//   node tools/stadtplan-links.mjs
import { writeFileSync } from "node:fs";
import { loadGame, boot } from "../lib/cutaway/tools/lib/game.mjs";

const g = loadGame("index.html");
await boot(g, { instant: true });
const C = g.C;
const walked = new Set(C.room.ids().filter((id) => { const r = C.room.get(id); return r.walk && !r.observe && !r.feed; }));

/** where a hotspot is: its walk-to point, else the middle of its shape */
const placeOf = (h) => {
  if (h.walkTo) return h.walkTo.slice(0, 2);
  const s = h.rect ? [h.rect[0] + h.rect[2] / 2, h.rect[1] + h.rect[3] / 2] : null;
  if (s) return s;
  if (h.poly) { let x = 0, y = 0; for (let i = 0; i < h.poly.length; i += 2) { x += h.poly[i]; y += h.poly[i + 1]; } return [x / (h.poly.length / 2), y / (h.poly.length / 2)]; }
  return null;
};
/** every goto in a script, with the conditions it is under */
function gotos(s, out, cond = []) {
  if (Array.isArray(s)) { for (const x of s) gotos(x, out, cond); return out; }
  if (!s || typeof s !== "object") return out;
  if (typeof s.goto === "string") out.push({ to: s.goto, at: s.at ?? null, cond: cond.join(" & ") });
  const c = "if" in s ? (typeof s.if === "string" ? s.if : JSON.stringify(s.if)) : null;
  for (const [k, v] of Object.entries(s)) if (k !== "if" && v && typeof v === "object") gotos(v, out, c === null ? cond : [...cond, k === "else" ? `!(${c})` : c]);
  return out;
}

const links = [];
for (const id of walked) {
  const r = C.room.get(id);
  for (const [hid, h] of Object.entries(r.hotspots ?? {})) {
    const at = placeOf(h), name = typeof h.name === "string" ? h.name : hid;
    if (h.exit && walked.has(h.exit.to)) links.push({ from: id, hotspot: hid, name, at, to: h.exit.to, toAt: h.exit.at ?? null, kind: "exit", cond: "" });
    for (const k of ["use", "look", "talk", "with"]) {
      const s = k === "with" ? Object.values(h.with ?? {}) : h[k];
      for (const gt of gotos(s, [])) if (walked.has(gt.to) && gt.to !== id) links.push({ from: id, hotspot: hid, name, at, to: gt.to, toAt: gt.at, kind: "goto", cond: gt.cond });
    }
  }
}
// one arrow per way (the same hotspot to the same room once, whatever the conditions)
const seen = new Set(), out = links.filter((l) => { const k = `${l.from}/${l.hotspot}/${l.to}`; if (seen.has(k)) return false; seen.add(k); return true; });
writeFileSync("docs/plan/uebergaenge.js", "// generated by tools/stadtplan-links.mjs from the game (hotspots' exits and gotos between the rooms Juno walks): never edit\n" +
  "\"use strict\";\n\nvar STADTPLAN_ROOMS = " + JSON.stringify([...walked].sort()) + ";\nvar STADTPLAN_LINKS = [\n" +
  out.map((l) => "  " + JSON.stringify(l)).join(",\n") + ",\n];\n");
console.log(`docs/plan/uebergaenge.js: ${walked.size} rooms walked, ${out.length} ways`);
