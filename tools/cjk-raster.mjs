// Rasterise CJK glyphs from a system font in headless Chrome into "#"/"." rows, for layout tests only (SimSun
// is Microsoft's and must not ship). Usage: node tools/cjk-raster.mjs "12px SimSun" 12 art/test/cjk_glyphs.js art/test/cjk_texts.txt
import { launch } from "../lib/cutaway/tools/lib/chrome.mjs";
import { readFileSync, writeFileSync } from "node:fs";
const [font, size, out, textFile] = process.argv.slice(2);
const chars = [...new Set([...readFileSync(textFile, "utf8")].filter((ch) => ch.charCodeAt(0) > 0x2e7f))].join("");
const b = await launch({ width: 400, height: 300 });
await b.send("Page.navigate", { url: "about:blank" });
await new Promise((r) => setTimeout(r, 300));
const res = await b.ev(`(() => {
  const n = ${Number(size)}, c = document.createElement("canvas"); c.width = n + 4; c.height = n + 4;
  const g = c.getContext("2d", { willReadFrequently: true }); const out = {};
  for (const ch of ${JSON.stringify(chars)}) {
    g.clearRect(0, 0, c.width, c.height); g.fillStyle = "#000"; g.font = ${JSON.stringify(font)}; g.textBaseline = "top";
    g.fillText(ch, 0, 0);
    const d = g.getImageData(0, 0, n, n).data, rows = [];
    for (let y = 0; y < n; y++) { let r = ""; for (let x = 0; x < n; x++) r += d[(y * n + x) * 4 + 3] > 110 ? "#" : "."; rows.push(r); }
    out[ch] = rows;
  }
  return out;
})()`);
await b.close();
writeFileSync(out, `// generated by tools/cjk-raster.mjs (${font}): a test only\nconst CJK_GLYPHS = ${JSON.stringify(res)}\n`);
console.log(Object.keys(res).length, "glyphs");
