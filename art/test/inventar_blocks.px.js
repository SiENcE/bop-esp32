const ITEMS = ["ausweis", "haken", "stick", "tap", "reis", "suppe"]
// the sheet's labels: painted text is English, even on a review sheet (the ids stay as the game names them)
const LABEL = { ausweis: "ID CARD", haken: "HOOK", stick: "STICK", tap: "TAP", reis: "RICE", suppe: "BROTH" }

// ---------------------------------------------------------------- the sheet
const CW = 36, X0 = 14
scene("inventar_blocks", { w: X0 + ITEMS.length * CW + 2, h: 56, bg: "z" },
  (c) => {
    ITEMS.forEach((it, i) => TXT.draw(c, X0 + i * CW + CW / 2, 4, LABEL[it], "6", { font: "hud", align: "center" }))
    TXT.draw(c, 4, 19, "A", "G", { font: "hud" })
    TXT.draw(c, 4, 39, "B", "G", { font: "hud" })
  },
  ...ITEMS.flatMap((it, i) => [
    stamp(`inv_${it}_a`, X0 + i * CW + 8, 14),
    stamp(`inv_${it}_b`, X0 + i * CW + 8, 34),
  ]))

// ---------------------------------------------------------------- the bag, open, with the A set
